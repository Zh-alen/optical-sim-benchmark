class TestBCH255Roundtrip:

    def test_encode_decode_roundtrip(self):
        """Encode random messages, introduce errors, decode."""
        from commplax.fec.ofec import _bch255_encode, _bch255_decode
        rng = np.random.default_rng(123)

        for trial in range(50):
            msg = rng.integers(0, 2, 239)
            cw = _bch255_encode(msg)

            # No errors
            dec, nerr = _bch255_decode(cw)
            assert nerr == 0
            np.testing.assert_array_equal(dec[16:], msg)

            # 1 error
            cw1 = cw.copy()
            pos = rng.integers(0, 255)
            cw1[pos] ^= 1
            dec1, nerr1 = _bch255_decode(cw1)
            assert nerr1 == 1, f"Trial {trial}: expected 1 error"
            np.testing.assert_array_equal(dec1[16:], msg)

            # 2 errors
            cw2 = cw.copy()
            pos2 = rng.choice(255, 2, replace=False)
            cw2[pos2] ^= 1
            dec2, nerr2 = _bch255_decode(cw2)
            assert nerr2 == 2, f"Trial {trial}: expected 2 errors at {pos2}"
            np.testing.assert_array_equal(dec2[16:], msg)


