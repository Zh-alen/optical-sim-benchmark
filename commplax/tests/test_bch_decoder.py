# GF(2^8) arithmetic tests
# =====================================================================

class TestGF256:

    def test_exp_table_matches_matlab(self, gf, matlab_vectors):
        exp_matlab = matlab_vectors["exp_tbl"].astype(int)
        # MATLAB exp_tbl is 1-indexed with 256 entries (alpha^0..alpha^255)
        # Our exp_tbl is 0-indexed with 256 entries
        np.testing.assert_array_equal(gf.exp_table[:256], exp_matlab[:256])

    def test_log_table_matches_matlab(self, gf, matlab_vectors):
        log_matlab = matlab_vectors["log_tbl"].astype(int)
        # MATLAB log_tbl(v+1) = log_alpha(v) for v=1..255
        for v in range(1, 256):
            assert gf.log_table[v] == log_matlab[v], f"log({v})"

    def test_primitive_element(self, gf):
        """alpha^255 = 1 (primitive element has order 255)."""
        val = 1
        for _ in range(255):
            val = gf.mul(val, 2)  # multiply by alpha
        assert val == 1

    def test_mul_inverse(self, gf):
        """a * a^(-1) = 1 for all nonzero a."""
        for a in range(1, 256):
            a_inv = gf.inv(a)
            assert gf.mul(a, a_inv) == 1, f"a={a}, inv={a_inv}"

    def test_add_is_xor(self, gf):
        assert gf.add(0b10110, 0b11001) == 0b10110 ^ 0b11001


