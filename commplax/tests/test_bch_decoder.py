class TestBCH255Decoder:

    def test_decode_no_errors(self, matlab_vectors):
        from commplax.fec.ofec import _bch255_decode
        codewords = matlab_vectors["codewords"].astype(int)
        msgs = matlab_vectors["msgs"].astype(int)
        n = int(matlab_vectors["n"])
        k = int(matlab_vectors["k"])

        for i in range(codewords.shape[0]):
            cw_poly = codewords[i, :n][::-1]
            decoded, num_err = _bch255_decode(cw_poly)
            # Reverse back to MSB-first for message comparison
            msg_msb = decoded[::-1][:k]  # take first k bits in MSB order
            assert num_err == 0, f"Test {i}: expected 0 errors, got {num_err}"
            np.testing.assert_array_equal(
                msg_msb, msgs[i],
                err_msg=f"Test {i}: decoded message mismatch (0 errors)"
            )

    def test_decode_single_error(self, matlab_vectors):
        from commplax.fec.ofec import _bch255_decode
        rx_1err = matlab_vectors["rx_1err"].astype(int)
        msgs = matlab_vectors["msgs"].astype(int)
        n = int(matlab_vectors["n"])
        k = int(matlab_vectors["k"])

        for i in range(rx_1err.shape[0]):
            rx_poly = rx_1err[i, :n][::-1]
            decoded, num_err = _bch255_decode(rx_poly)
            msg_msb = decoded[::-1][:k]
            assert num_err == 1, f"Test {i}: expected 1 error, got {num_err}"
            np.testing.assert_array_equal(
                msg_msb, msgs[i],
                err_msg=f"Test {i}: decoded message mismatch (1 error)"
            )

    def test_decode_double_error(self, matlab_vectors):
        from commplax.fec.ofec import _bch255_decode
        rx_2err = matlab_vectors["rx_2err"].astype(int)
        msgs = matlab_vectors["msgs"].astype(int)
        n = int(matlab_vectors["n"])
        k = int(matlab_vectors["k"])

        for i in range(rx_2err.shape[0]):
            rx_poly = rx_2err[i, :n][::-1]
            decoded, num_err = _bch255_decode(rx_poly)
            msg_msb = decoded[::-1][:k]
            assert num_err == 2, f"Test {i}: expected 2 errors, got {num_err}"
            np.testing.assert_array_equal(
                msg_msb, msgs[i],
                err_msg=f"Test {i}: decoded message mismatch (2 errors)"
            )

    def test_decode_triple_error_detected(self, matlab_vectors):
        """3 errors should be detected as uncorrectable."""
        from commplax.fec.ofec import _bch255_decode
        rx_3err = matlab_vectors.get("rx_3err")
        if rx_3err is None:
            pytest.skip("No 3-error test vectors")
        rx_3err = rx_3err.astype(int)
        n = int(matlab_vectors["n"])

        detected = 0
        for i in range(rx_3err.shape[0]):
            rx_poly = rx_3err[i, :n][::-1]
            _, num_err = _bch255_decode(rx_poly)
            if num_err == -1:
                detected += 1
        # Not all 3-error patterns are detectable
        assert detected > 0, "Should detect at least some 3-error patterns"


