class TestSyndromes:

    def test_zero_syndrome_for_valid_codeword(self, matlab_vectors):
        from commplax.fec.ofec import _bch255_syndromes, _GF256
        codewords = matlab_vectors["codewords"].astype(int)
        n = int(matlab_vectors["n"])

        for i in range(codewords.shape[0]):
            # MSB-first: reverse to get polynomial coefficient order
            cw_poly = codewords[i, :n][::-1]  # coeff of x^0 first
            S = _bch255_syndromes(cw_poly)
            assert S[0] == 0 and S[1] == 0 and S[2] == 0 and S[3] == 0, \
                f"Test {i}: syndromes not zero for valid codeword"

    def test_single_error_syndrome(self, matlab_vectors):
        from commplax.fec.ofec import _bch255_syndromes, _GF256
        rx_1err = matlab_vectors["rx_1err"].astype(int)
        syndromes_1err = matlab_vectors["syndromes_1err"].astype(int)
        n = int(matlab_vectors["n"])

        for i in range(rx_1err.shape[0]):
            rx_poly = rx_1err[i, :n][::-1]
            S = _bch255_syndromes(rx_poly)
            np.testing.assert_array_equal(
                S, syndromes_1err[i],
                err_msg=f"Test {i}: 1-error syndrome mismatch"
            )

    def test_double_error_syndrome(self, matlab_vectors):
        from commplax.fec.ofec import _bch255_syndromes, _GF256
        rx_2err = matlab_vectors["rx_2err"].astype(int)
