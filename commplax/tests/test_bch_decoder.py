class TestJAXDecoder:

    def test_jax_decoder_matches_numpy(self):
        """JAX decoder gives same results as numpy reference for all error cases."""
        import jax.numpy as jnp
        from commplax.fec.ofec import (
            _bch256_encode, _bch256_decode, _bch256_decode_jax
        )
        rng = np.random.default_rng(888)
        for trial in range(30):
            msg = rng.integers(0, 2, 239)
            cw = _bch256_encode(msg)

            # Pick 0, 1, or 2 errors
            n_errors = trial % 3
            rx = cw.copy()
            if n_errors == 1:
                pos = rng.integers(0, 256)
                rx[pos] ^= 1
            elif n_errors == 2:
                pos2 = rng.choice(256, 2, replace=False)
                rx[pos2] ^= 1

            dec_np, nerr_np = _bch256_decode(rx)
            dec_jax, nerr_jax = _bch256_decode_jax(jnp.array(rx))

            assert int(nerr_jax) == nerr_np, \
                f"Trial {trial}: nerr mismatch: JAX={int(nerr_jax)} vs np={nerr_np}"
            np.testing.assert_array_equal(
                np.asarray(dec_jax), dec_np,
                err_msg=f"Trial {trial}: corrected codeword mismatch"
            )

    def test_jax_decoder_jit(self):
        """JAX decoder works under jit compilation."""
        import jax
        import jax.numpy as jnp
        from commplax.fec.ofec import _bch256_decode_jax

        decode_jit = jax.jit(_bch256_decode_jax)

        rng = np.random.default_rng(999)
        msg = rng.integers(0, 2, 239)
        from commplax.fec.ofec import _bch256_encode
        cw = _bch256_encode(msg)

        # No errors
        dec, nerr = decode_jit(jnp.array(cw))
        assert int(nerr) == 0

        # 1 error
        rx1 = cw.copy()
        rx1[100] ^= 1
        dec1, nerr1 = decode_jit(jnp.array(rx1))
        assert int(nerr1) == 1
        np.testing.assert_array_equal(np.asarray(dec1)[16:255], msg)

        # 2 errors
        rx2 = cw.copy()
        rx2[50] ^= 1
        rx2[200] ^= 1
        dec2, nerr2 = decode_jit(jnp.array(rx2))
        assert int(nerr2) == 2
        np.testing.assert_array_equal(np.asarray(dec2)[16:255], msg)

    def test_jax_decoder_vmap(self):
        """JAX decoder works with vmap for batch decoding."""
        import jax
        import jax.numpy as jnp
        from commplax.fec.ofec import _bch256_encode, _bch256_decode_jax

        decode_batch = jax.vmap(_bch256_decode_jax)

        rng = np.random.default_rng(1111)
        batch_size = 16
        batch_rx = np.zeros((batch_size, 256), dtype=np.int32)
        expected_msgs = np.zeros((batch_size, 239), dtype=np.int32)
        expected_nerrs = np.zeros(batch_size, dtype=np.int32)

        for i in range(batch_size):
            msg = rng.integers(0, 2, 239)
            expected_msgs[i] = msg
            cw = _bch256_encode(msg)
            n_err = rng.integers(0, 3)  # 0, 1, or 2 errors
            rx = cw.copy()
            if n_err >= 1:
                pos = rng.integers(0, 255)
                rx[pos] ^= 1
            if n_err >= 2:
                pos2 = rng.integers(0, 255)
                while pos2 == pos:
                    pos2 = rng.integers(0, 255)
                rx[pos2] ^= 1
            batch_rx[i] = rx
            expected_nerrs[i] = n_err

        dec_batch, nerr_batch = decode_batch(jnp.array(batch_rx))

        np.testing.assert_array_equal(np.asarray(nerr_batch), expected_nerrs)
        for i in range(batch_size):
            np.testing.assert_array_equal(
                np.asarray(dec_batch[i])[16:255], expected_msgs[i],
                err_msg=f"Batch item {i}: message mismatch"
            )
