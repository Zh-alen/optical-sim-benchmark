class TestJAXEncoder:

    def test_jax_encoder_matches_numpy(self):
        """JAX _bch_encode_systematic matches numpy _bch256_encode."""
        import jax.numpy as jnp
        from commplax.fec.ofec import _bch256_encode, _bch_encode_systematic
        rng = np.random.default_rng(555)
        for _ in range(20):
            msg = rng.integers(0, 2, 239)
            cw_np = _bch256_encode(msg)
            cw_jax = np.asarray(_bch_encode_systematic(jnp.array(msg)))
            np.testing.assert_array_equal(cw_np, cw_jax)

    def test_jax_encoder_roundtrip(self):
        """JAX encode → numpy decode roundtrip."""
        import jax.numpy as jnp
        from commplax.fec.ofec import _bch_encode_systematic, _bch256_decode
        rng = np.random.default_rng(666)
        for trial in range(20):
            msg = rng.integers(0, 2, 239)
            cw = np.asarray(_bch_encode_systematic(jnp.array(msg)))
            # Introduce 1 error
            pos = rng.integers(0, 256)
            rx = cw.copy()
            rx[pos] ^= 1
            dec, nerr = _bch256_decode(rx)
            assert nerr == 1, f"Trial {trial}: expected 1, got {nerr}"
            np.testing.assert_array_equal(dec[16:255], msg)

    def test_bch256_239_api(self):
        """BCH256_239() encode/decode API works correctly."""
        import jax.numpy as jnp
        from commplax.fec.ofec import BCH256_239
        encode, decode = BCH256_239()
        rng = np.random.default_rng(777)
        for trial in range(10):
            msg = rng.integers(0, 2, 239)
            cw = encode(jnp.array(msg))
            # Introduce 2 errors
            rx = np.asarray(cw).copy()
            pos2 = rng.choice(255, 2, replace=False)
            rx[pos2] ^= 1
            decoded_msg, nerr = decode(jnp.array(rx))
            assert nerr == 2, f"Trial {trial}: expected 2, got {nerr}"
            np.testing.assert_array_equal(np.asarray(decoded_msg), msg)


